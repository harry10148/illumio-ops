"""The PCE event types an event alert rule can name, by category (5.x parity 2026-11-06: 5.x src/events/catalog.py,
its descriptions from the Events Administration Guide). The catalog is a picker: a rule may still name a type it does
not list (a newer PCE sends types this build does not know), or a pattern.

status_filter / severity_filter: the types 5.x marked as coming with more than one status or severity — the sign-in and
API request events (success and failure) — plus agent.refresh_policy for status, which the best-practice pack watches
for failures. Every event carries both fields and a rule may set either on any type; the marks only tell the editor
which types are known to vary (5.x's own list, kept as it was: agent.tampering, for one, arrives as info and warning).
"""
