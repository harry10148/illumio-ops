// contracts.json (exported from the Python API contracts) -> src/api/generated.ts.
// Run through scripts/v6/gen_contracts.sh; never edit generated.ts by hand.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = JSON.parse(readFileSync(join(here, "../src/api/contracts.json"), "utf8"));
const defs = {};

function addDef(name, schema) {
  const prev = defs[name];
  if (prev && JSON.stringify(prev) !== JSON.stringify(schema)) {
    throw new Error(`two different models are both named ${name}; rename one`);
  }
  defs[name] = schema;
}

// pydantic titles every field; json-schema-to-typescript would turn each into a type
// alias. Keep titles on models only.
function stripFieldTitles(node, isProperty = false) {
  if (Array.isArray(node)) return node.map((n) => stripFieldTitles(n, isProperty));
  if (!node || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "title" && isProperty) continue;
    if (k === "properties") {
      out[k] = Object.fromEntries(Object.entries(v).map(([pk, pv]) => [pk, stripFieldTitles(pv, true)]));
    } else if (k === "anyOf" || k === "oneOf" || k === "allOf" || k === "items" || k === "additionalProperties") {
      out[k] = stripFieldTitles(v, isProperty);
    } else if (k === "$defs") {
      out[k] = Object.fromEntries(Object.entries(v).map(([dk, dv]) => [dk, stripFieldTitles(dv)]));
    } else {
      out[k] = v;
    }
  }
  return out;
}

function register(raw) {
  if (!raw) return null;
  const schema = stripFieldTitles(raw);
  const { $defs = {}, ...top } = schema;
  for (const [name, sub] of Object.entries($defs)) addDef(name, sub);
  addDef(top.title, top);
  return top.title;
}

const ops = Object.keys(contracts.operations).sort();
const names = {};
for (const op of ops) {
  const c = contracts.operations[op];
  names[op] = { req: register(c.request_schema), res: register(c.response_schema) };
}

const root = { title: "ContractRoot", type: "object", additionalProperties: false, properties: {}, $defs: defs };
let types = await compile(root, "ContractRoot", {
  bannerComment: "",
  additionalProperties: false,
  unreachableDefinitions: true,
  format: false,
});
types = types.replace(/export interface ContractRoot \{\s*\}\n?/, "");

const q = (s) => JSON.stringify(s);
const lines = [
  "// Generated by web/scripts/gen-types.mjs from src/api/contracts.json. Do not edit.",
  "/* eslint-disable */",
  types.trim(),
  "",
  `export type OpId = ${ops.map(q).join(" | ")};`,
  "",
  "export interface Requests {",
  ...ops.map((op) => `  ${q(op)}: ${names[op].req ?? "undefined"};`),
  "}",
  "",
  "export interface Responses {",
  ...ops.map((op) => `  ${q(op)}: ${names[op].res};`),
  "}",
  "",
  "export const OPERATIONS = {",
  ...ops.map((op) => {
    const c = contracts.operations[op];
    return `  ${q(op)}: { method: ${q(c.method)}, path: ${q(c.path)} },`;
  }),
  "} as const satisfies Record<OpId, { method: string; path: string }>;",
  "",
  `export const VALUES = ${JSON.stringify(contracts.values, null, 2)} as const;`,
  "",
];
writeFileSync(join(here, "../src/api/generated.ts"), lines.join("\n"));
